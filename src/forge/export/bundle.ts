/**
 * Construit le dossier autonome exporté :
 *   <kebab-name>/index.tsx | index.jsx, styles.css, README.md, ui/*.tsx (sources des primitives utilisées)
 * Aucun import du studio : seulement React et les bibliothèques réellement utilisées.
 */
import { transform } from "sucrase";
import { tr } from "../../i18n/core";
import type { ComponentDoc } from "../model/types";
import { toKebab } from "../model/ops";
import { generateTsx, type GenResult } from "../codegen/tsx";
import { generateCss, scopeClass } from "../codegen/css";
import { NPM_VERSIONS, VENDOR_SOURCES } from "../generated/vendor-sources";
import { FONT_LICENSES, NPM_LICENSES, THIRD_PARTY, type ThirdParty } from "../licenses/third-party";

export type ExportOptions = { language: "tsx" | "jsx" };
export type ExportBundle = {
  folder: string;
  files: Record<string, string>;
  npm: string[];
  installCommand: string;
  gen: GenResult;
};

export function toJs(tsx: string, file = "index.tsx"): string {
  const out = transform(tsx, { transforms: ["typescript", "jsx"], jsxRuntime: "preserve", disableESTransforms: true, filePath: file }).code;
  // sucrase laisse des lignes vides là où étaient les types : on compacte
  return out.replace(/\n{3,}/g, "\n\n").replace(/^\s*;\s*$/gm, "");
}

/** En JavaScript, les props sont documentées en JSDoc : autocomplétion + props optionnelles pour TypeScript */
function withJsDoc(js: string, gen: GenResult): string {
  const doc = [
    "/**",
    ` * ${gen.componentName}`,
    " * @param {Object} props",
    ...gen.props.map((p) => ` * @param {${p.type}} [props.${p.name}] ${p.comment}${p.defaultValue ? ` (${tr("default: {value}", { value: p.defaultValue })})` : ""}`),
    " */",
  ].join("\n");
  return js.replace(/^export default function /m, `${doc}\nexport default function `);
}

/** Bibliothèques tierces réellement présentes (copiées ou adaptées) dans cet export */
export function thirdPartiesOf(doc: ComponentDoc, vendoredFiles: string[]): ThirdParty[] {
  const ids = new Set<string>();
  for (const f of vendoredFiles) {
    const v = VENDOR_SOURCES[f];
    if (!v) continue;
    ids.add(v.origin);
    v.derived.forEach((d) => ids.add(d));
  }
  if (doc.theme.preset?.id === "beautiful-ui" || Object.values(doc.nodes).some((n) => n.animation?.origin === "beautiful-ui")) ids.add("beautiful-ui");
  return [...ids].map((id) => THIRD_PARTY[id]).filter(Boolean);
}

export function usesPresetFonts(doc: ComponentDoc) {
  const all = Object.values(doc.theme.font).join(" ");
  return FONT_LICENSES.filter((f) => all.includes(f.name));
}

export function thirdPartyNotices(doc: ComponentDoc, vendoredFiles: string[], npm: string[]): string {
  const parties = thirdPartiesOf(doc, vendoredFiles);
  const fonts = usesPresetFonts(doc);
  const lines: string[] = [
    tr("# Third-party notices (THIRD_PARTY_NOTICES)"),
    "",
    tr("The {name} component (index, styles.css except the sections marked below) was generated by UI Forge and belongs to its author.", { name: doc.name }),
    tr("The elements below come from third-party libraries and remain subject to their original license."),
    tr("Copyright headers of the copied files, if any, are kept."),
    "",
  ];
  if (!parties.length) lines.push(tr("No third-party code is copied into this folder."), "");
  for (const p of parties) {
    lines.push(`## ${p.name} — ${p.license}`, "", `- ${p.copyright}`, `- ${tr("Source:")} ${tr(p.source)}`, `- ${tr("Used here:")} ${tr(p.usedFor)}`, "", "```", p.text, "```", "");
  }
  if (npm.length) {
    lines.push(tr("## npm dependencies (installed separately, not included in this folder)"), "");
    for (const n of npm) lines.push(`- \`${n}\` — ${NPM_LICENSES[n] ?? tr("see node_modules/{name}/LICENSE", { name: n })}`);
    lines.push("");
  }
  if (fonts.length) {
    lines.push(tr("## Referenced fonts (not included)"), "");
    for (const f of fonts) lines.push(`- ${f.name} — ${f.license} — ${f.copyright} — ${f.source}`);
    lines.push("");
  }
  return lines.join("\n");
}

export function collectVendored(entry: string[]) {
  const files = new Set<string>();
  const npm = new Set<string>();
  const visit = (f: string) => {
    if (files.has(f)) return;
    const v = VENDOR_SOURCES[f];
    if (!v) return;
    files.add(f);
    v.npm.forEach((n) => npm.add(n));
    v.local.forEach(visit);
  };
  entry.forEach(visit);
  return { files: [...files].sort(), npm };
}

export function readme(doc: ComponentDoc, gen: GenResult, folder: string, install: string, lang: "tsx" | "jsx", vendored: string[], parties: ThirdParty[] = []) {
  const fonts = usesPresetFonts(doc);
  const fontSection = fonts.length
    ? `\n${tr("## Fonts")}\n\n${tr("This theme uses {fonts} (SIL OFL 1.1 license). The font files are not included:", { fonts: fonts.map((f) => f.name).join(" & ") })}\n${tr("load them with `next/font` in your layout, otherwise a system fallback font is used.")}\n\n\`\`\`tsx\n// app/layout.tsx\nimport { ${fonts.map((f) => f.name.replace(/\s/g, "_")).join(", ")} } from "next/font/google";\n${fonts
        .map((f) => `const ${f.name === "Inter" ? "inter" : "mono"} = ${f.name.replace(/\s/g, "_")}({ subsets: ["latin"], variable: "${f.name === "Inter" ? "--font-inter" : "--font-jetbrains-mono"}" });`)
        .join("\n")}\n// <html className={\`${fonts.map((f) => `\${${f.name === "Inter" ? "inter" : "mono"}.variable}`).join(" ")}\`}>\n\`\`\`\n`
    : "";
  const preset = doc.theme.preset
    ? `\n${tr("Theme based on the **{name}** preset ({source}, {license} license, {copyright}).", { name: doc.theme.preset.name, source: doc.theme.preset.source, license: doc.theme.preset.license, copyright: doc.theme.preset.copyright })}\n`
    : "";
  const name = gen.componentName;
  const example = gen.props.filter((p) => p.type === "string" && p.defaultValue).slice(0, 2);
  const custom = example.length ? `<${name} ${example.map((p) => `${p.name}="…"`).join(" ")} />` : `<${name} />`;
  const table = gen.props
    .map((p) => `| \`${p.name}\` | \`${p.type.replace(/\|/g, "\\|")}\` | ${p.defaultValue ? `\`${p.defaultValue.replace(/\|/g, "\\|")}\`` : "—"} | ${p.comment} |`)
    .join("\n");
  return `# ${name}

${tr("Self-contained React component exported from UI Forge.")}

${tr("## 1. Install the dependencies")}

\`\`\`bash
${install}
\`\`\`

${tr("Requirements: React 19 and **Tailwind CSS v4** (installed by default with `create-next-app`).")}
${tr("No theme configuration is needed: colors, radii, spacing and fonts are")}
${tr("CSS variables defined in `styles.css`, scoped to this component.")}

${tr("## 2. Drop in the folder")}

${tr("Copy the `{folder}/` folder into your project, for example into `components/{folder}/`.", { folder })}

${tr("## 3. Use it in one line")}

\`\`\`tsx
import ${name} from "@/components/${folder}";

${gen.usage}
\`\`\`

${tr("With your own texts:")}

\`\`\`tsx
${custom}
\`\`\`

${tr("## Props")}

${tr("All props are optional.")}

| ${tr("Prop")} | ${tr("Type")} | ${tr("Default")} | ${tr("Description")} |
| --- | --- | --- | --- |
${table}

${tr("## Folder contents")}

- \`index.${lang}\`${tr(": the component (single entry point, `\"use client\"`)")}
- \`styles.css\`${tr(": tokens (CSS variables) and styles of the component, imported by `index.{lang}`", { lang })}
${vendored.map((f) => `- \`${f}\`${tr(": primitive copied from its original library (editable)")}`).join("\n")}

${tr("## Customize the theme")}

${tr("Edit the variables at the top of `styles.css` (`.{scope}` block),", { scope: scopeClass(doc) })}
${tr("or pass `colorScheme=\"dark\" | \"auto\"` for dark mode.")}
${preset}${fontSection}
${tr("## Licenses")}

${tr("The generated code (`index.{lang}` and the component styles) belongs to you: use it freely.", { lang })}
${tr("Only third-party files and snippets are subject to their original license")}
${parties.length ? `(${parties.map((p) => `${p.name} — ${p.license}`).join(", ")})` : ""}${tr(": see `THIRD_PARTY_NOTICES.md`.")}
`;
}

export function buildExport(doc: ComponentDoc, opts: ExportOptions = { language: "tsx" }): ExportBundle {
  const gen = generateTsx(doc);
  const folder = toKebab(gen.componentName) || "mon-composant";
  const css = generateCss(doc);
  const vend = collectVendored(gen.vendored);
  const npm = new Set<string>([...gen.npm, ...vend.npm]);
  npm.delete("react");
  npm.delete("react-dom");
  const pkgs = [...npm].sort();
  const installCommand = pkgs.length ? `npm install ${pkgs.map((p) => (NPM_VERSIONS[p] ? `${p}@${NPM_VERSIONS[p]}` : p)).join(" ")}` : `# ${tr("no additional dependency")}`;

  const files: Record<string, string> = {};
  const isJs = opts.language === "jsx";
  files[`index.${opts.language}`] = isJs ? withJsDoc(toJs(gen.code), gen) : gen.code;
  files["styles.css"] = css;
  for (const f of vend.files) {
    const code = VENDOR_SOURCES[f].code;
    files[isJs ? f.replace(/\.tsx$/, ".jsx") : f] = isJs ? toJs(code, f) : code;
  }
  const parties = thirdPartiesOf(doc, vend.files);
  files["README.md"] = readme(doc, gen, folder, installCommand, opts.language, vend.files.map((f) => (isJs ? f.replace(/\.tsx$/, ".jsx") : f)), parties);
  files["THIRD_PARTY_NOTICES.md"] = thirdPartyNotices(doc, vend.files, pkgs);
  return { folder, files, npm: pkgs, installCommand, gen };
}

export async function buildZip(bundle: ExportBundle): Promise<Blob> {
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  const dir = zip.folder(bundle.folder)!;
  for (const [path, content] of Object.entries(bundle.files)) dir.file(path, content);
  return zip.generateAsync({ type: "blob" });
}
